"""Build the supervised fine-tuning files that teach gpt-4.1-mini to read Indian cheque papers into Tarikh's fields.

Every paper is generated by tools/make_samples.py from invented scenarios, so no real person's cheque is used.
Each line is one chat example: the same instruction the ModelExtractor sends, one image, and the exact JSON answer.
    python -m tools.make_finetune            ->  data/finetune/train.jsonl (30 examples), validation.jsonl (9)"""
from __future__ import annotations

import base64
import io
import json
import random
from dataclasses import replace
from datetime import timedelta
from pathlib import Path

from app.analyzers import FIELD_SPECS
from app.models import DocType
from tools.make_samples import Scenario, band, make_cheque, make_memo, make_notice, photoize

OUT = Path("data/finetune")
PROMPT = ("Read this Indian banking paper. Return each field exactly as printed. Dates as YYYY-MM-DD "
          "(Indian papers write the day first). Amounts as digits only. Use null when a field is not visible; never guess.")
ONES = "Zero One Two Three Four Five Six Seven Eight Nine Ten Eleven Twelve Thirteen Fourteen Fifteen Sixteen Seventeen Eighteen Nineteen".split()
TENS = "_ _ Twenty Thirty Forty Fifty Sixty Seventy Eighty Ninety".split()


def words(n: int) -> str:
    def two(x):
        return ONES[x] if x < 20 else TENS[x // 10] + ("-" + ONES[x % 10] if x % 10 else "")
    parts = []
    for size, name in ((10_000_000, "Crore"), (100_000, "Lakh"), (1000, "Thousand"), (100, "Hundred")):
        if n >= size:
            parts.append(f"{two(n // size)} {name}"); n %= size
    if n:
        parts.append(two(n))
    return " ".join(parts) + " only"


DRAWERS = ["Kalra Fabricators", "Dhillon Cold Storage", "Mehra Agro Supplies", "Rana Medicos", "Preet Bakers", "Hans Builders",
           "Bhatia Timber Mart", "Verma Builders", "Goyal Traders", "Pal Printers", "Sekhon Hardware", "Ahuja Tyres", "Walia Textiles"]
PAYEES = ["Sharma Steel Traders", "Bajwa Agro Inputs", "Gill Tractors", "Sethi Pharma Distributors", "Arora Packaging",
          "Chawla Hardware", "Northline Finance", "Saini Electricals", "Anand Grains", "Luthra Paper Mart", "Kohli Motors", "Brar Seeds", "Jain Cement"]
BANKS = [("Northern Sample Bank", "Sector 22 Branch, Chandigarh"), ("Sample Co-operative Bank", "Model Town, Ludhiana"),
         ("Sample Urban Bank", "Phase 7, Mohali"), ("Northern Sample Bank", "Lawrence Road, Amritsar")]
REASONS = [("51", "FUNDS INSUFFICIENT"), ("02", "PAYMENT STOPPED BY DRAWER"), ("16", "ACCOUNT CLOSED"),
           ("21", "DRAWER'S SIGNATURE DIFFERS"), ("52", "EXCEEDS ARRANGEMENT")]


def scenario(i: int, r: random.Random) -> Scenario:
    base = Scenario()
    cd = base.cheque_date + timedelta(days=r.randint(-300, 40))
    pres = cd + timedelta(days=r.randint(3, 40)); memo = pres + timedelta(days=r.randint(1, 3))
    amount = r.choice([68000, 85000, 120000, 192500, 225000, 310000, 340000, 485000, 560000, 640000, 975000, 1440000])
    bank, branch = r.choice(BANKS); code, reason = r.choice(REASONS)
    return replace(base, drawer=DRAWERS[i % len(DRAWERS)], payee=PAYEES[i % len(PAYEES)], bank=bank, branch=branch,
                   cheque_no=f"{r.randint(1000, 999999):06d}", cheque_date=cd, presented_on=pres, memo_date=memo,
                   notice_date=memo + timedelta(days=r.randint(5, 25)), amount=amount, amount_words=words(amount),
                   reason=reason, reason_code=code)


def answer(t: DocType, s: Scenario) -> dict:
    a = {DocType.CHEQUE: {"cheque_number": s.cheque_no, "cheque_date": s.cheque_date.isoformat(), "amount_figures": str(s.amount),
                          "drawer_name": s.drawer.upper(), "payee_name": s.payee, "bank_name": s.bank.upper()},
         DocType.RETURN_MEMO: {"cheque_number": s.cheque_no, "presented_on": s.presented_on.isoformat(),
                               "return_date": s.memo_date.isoformat(), "return_reason": f"{s.reason_code} - {s.reason}"},
         DocType.DEMAND_NOTICE: {"cheque_number": s.cheque_no, "notice_date": s.notice_date.isoformat(), "demand_amount": str(s.amount)}}[t]
    assert set(a) == {f.key for f in FIELD_SPECS[t] if not f.manual}
    return {"fields": a}


def image_url(img, photo: bool, seed: int) -> str:
    band(img)
    if photo:
        img = photoize(img, seed)
    img = img.convert("RGB"); img.thumbnail((1280, 1280))
    buf = io.BytesIO(); img.save(buf, "JPEG", quality=72)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


def build(n: int, seed: int) -> list[dict]:
    r = random.Random(seed); rows = []
    for i in range(n):
        s = scenario(i + seed, r)
        for t, fn in ((DocType.CHEQUE, make_cheque), (DocType.RETURN_MEMO, make_memo), (DocType.DEMAND_NOTICE, make_notice)):
            rows.append({"messages": [
                {"role": "system", "content": PROMPT},
                {"role": "user", "content": [{"type": "text", "text": f"Paper type: {t.value}"},
                                             {"type": "image_url", "image_url": {"url": image_url(fn(s), i % 2 == 1, seed + i)}}]},
                {"role": "assistant", "content": json.dumps(answer(t, s))}]})
    return rows


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, n, seed in (("train", 10, 1), ("validation", 3, 101)):
        rows = build(n, seed)
        (OUT / f"{name}.jsonl").write_text("\n".join(json.dumps(x) for x in rows) + "\n", encoding="utf-8")
        print(f"{OUT / name}.jsonl: {len(rows)} examples, {(OUT / f'{name}.jsonl').stat().st_size / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
